export const coverLetterInstructions = `Напиши короткое, естественное сопроводительное письмо на русском от первого лица.

## Факты
Используй только подтверждённые факты из резюме и вакансии. Не выдумывай опыт, проекты, технологии, даты, метрики и достижения. Если чего-то нет в резюме — не добавляй.

## Отбор информации
Не стремись использовать все подходящие навыки и технологии из резюме.

Перед написанием определи:
1. Что является главным в вакансии.
2. Какой один наиболее сильный опыт кандидата это подтверждает.
3. Какой второй опыт можно добавить, если он действительно усиливает отклик.

Используй только эти 2–3 точки пересечения.

Если вакансия связана с AI, не перечисляй все AI/LLM-инструменты кандидата. Покажи конкретно, что он делал с AI.
Если вакансия связана с CRM, покажи реальный опыт с CRM, а не просто перечисляй API/BPMN/SQL.

## Адаптация под конкретную вакансию
Сопроводительное должно быть не пересказом резюме, а выборкой наиболее релевантного опыта под конкретную вакансию.

Перед написанием внутренне сделай маппинг, не показывая его в ответе:
вакансия → 2–3 ключевые задачи или требования → подтверждение из резюме → текст письма.

Начинай анализ с вакансии, а не с резюме. Не собирай сначала всё хорошее из резюме с последующей попыткой связать это с вакансией.

Каждый смысловой абзац должен быть связан хотя бы с одной из выбранных задач. Не упоминай опыт только потому, что он есть в резюме.

Если в вакансии названа конкретная предметная область, технология, тип продукта или способ работы и у кандидата есть соответствующий опыт, используй эту точную формулировку.

Не пересказывай требования вакансии и не пиши «вакансия предполагает...» или «в данной роли необходимо...». Связь с вакансией должна быть видна из выбора опыта и конкретных задач кандидата.

Выбирай опыт в таком порядке:
1. Прямое совпадение с задачей вакансии.
2. Близкий по смыслу опыт.
3. Остальной опыт — только если он заметно усиливает отклик.

Для разных вакансий выбирай разные факты из резюме. Не используй один и тот же набор проектов в каждом письме, если конкретная вакансия позволяет показать другие релевантные стороны опыта.

## Естественная структура
Не используй обязательную структуру «вступление → первый опыт → второй опыт → итоговый вывод».
Сопроводительное не должно выглядеть как аргументированное доказательство соответствия вакансии.

Начинай сразу с наиболее релевантного для конкретной вакансии опыта или задачи. Не обязательно представляться в первом предложении.

Не добавляй отдельный заключительный абзац с выводом о соответствии кандидата вакансии. Если связь между опытом и вакансией очевидна из текста, не нужно проговаривать её отдельно.

Не используй связки:
- «Думаю, мой опыт будет близок...»
- «Таким образом...»
- «Это позволяет мне...»
- «Именно поэтому...»
- «Считаю, что...»
- «Мой опыт хорошо соответствует...»
- «Всё это позволит мне...»

Предпочитай естественные переходы между мыслями или вообще не используй переход, если он не нужен.

Сопроводительное может состоять из 2–3 коротких абзацев и не обязано содержать формальное завершение.

Главное — создать ощущение, что кандидат сам написал этот текст после просмотра конкретной вакансии, а не заполнил шаблон «требование → подтверждение → вывод».
Не объясняй читателю, почему каждый приведённый опыт релевантен вакансии. Просто покажи релевантный опыт и конкретные задачи.

Не используй формулировки, описывающие качества кандидата через абстракции:
«системное мышление», «ориентация на результат», «коммуникационные навыки», «умение связывать бизнес и IT», если это не является прямым требованием вакансии.

Предпочитай действие вместо характеристики:
не «умею взаимодействовать с разработкой», а «ставил задачи разработке и сопровождал реализацию».

## Стиль: без AI-slop
Пиши как живой человек, коротко и конкретно.
- Без клише: «Меня заинтересовала ваша вакансия», «Я хотел бы выразить свой интерес», «Буду рад стать частью вашей команды», «Уверен, что мой опыт будет полезен вашей компании».
- Без контрастов «не X, а Y», «вопрос не в X, а в Y».
- Без разгонов: «вот в чём дело», «давайте прямо», «что обычно упускают», «никто не говорит».
- Без канцелярита и пустых слов: leverage, utilize, robust, cutting-edge, инновационный, комплексный, синергия, «в современном мире».
- Без драматичных обрывков и «глубоких» финальных афоризмов.
- Без перечисления всего стека. Название, цифры, результат важнее списка технологий.
- Не объясняй читателю, почему это важно. Покажи факт и действие.

Финальная фраза не обязательна. Если текст естественно заканчивается после основного тезиса, не добавляй формальный призыв к общению.

Верни только текст письма без заголовка, без пояснений и без разбора точек пересечения.`;

export function coverLetterPrompt(resume: string, vacancy: string) {
  return `${coverLetterInstructions}\n\nРЕЗЮМЕ:\n${resume}\n\nВАКАНСИЯ:\n${vacancy}`;
}
